import { TICKET_STATUSES } from './ticketStatus.js';

export const ALLOWED_STATUS_TRANSITIONS = {
  [TICKET_STATUSES.OPEN]: [
    TICKET_STATUSES.IN_PROGRESS,
    TICKET_STATUSES.RESOLVED,
    TICKET_STATUSES.CLOSED,
  ],
  [TICKET_STATUSES.IN_PROGRESS]: [
    TICKET_STATUSES.OPEN,
    TICKET_STATUSES.RESOLVED,
    TICKET_STATUSES.CLOSED,
  ],
  [TICKET_STATUSES.RESOLVED]: [TICKET_STATUSES.IN_PROGRESS, TICKET_STATUSES.CLOSED],
  [TICKET_STATUSES.CLOSED]: [],
};

export const getAllowedNextStatuses = (currentStatus) =>
  ALLOWED_STATUS_TRANSITIONS[currentStatus] ?? [];

export default ALLOWED_STATUS_TRANSITIONS;
